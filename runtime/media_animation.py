"""The runtime side of "Add an animation" (VD15, package V1b3): the catalogue of animations read as data, the listing the page offers, and the
check of an added animation's parameters by the renderer's own checker, through `MediaEngine` and its host verb `block-params`.

The rule of this module: the renderer's checker is the only checker of a block's parameters. This module never re-implements it. It reads the
generated catalogue (providers/renderer/blocks/catalogue.json) as data, only for a block's kind, preset and engines, and refuses it when its
`blocks_sha256` is not the sha256 of blocks/pins.json (the catalogue was not regenerated with the pins the render will load).

  read_catalogue(root)    the catalogue as data, our fields only, or a CatalogueError (`catalogue_unreadable`, `catalogue_stale`)
  engine_name(root, implementation=None)  the implementation the resolver gives `renderer:video` (the project's `media.renderer` when it names one), or None
  why_not(entry, engine)  why a block cannot be added now, or None
  listing(root, implementation=None)  what the operation `video-catalogue` returns
  checker(ctx)            the `animate(block, params, where)` callable that runtime/captions.py `apply_edits` takes

Standard library only. Runs on Python 3.9.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import re
import sys
import tempfile
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import captions  # noqa: E402
import ops_step_seams  # noqa: E402
import project_config  # noqa: E402

CLASS = "renderer:video"
VERB = "block-params"
CATALOGUE = ("providers", "renderer", "blocks", "catalogue.json")       # generated by the renderer (VD13); our fields only
PINS = ("providers", "renderer", "blocks", "pins.json")
VOCABULARY = "shared/references/video-presets.json"                     # = step_media.VOCABULARY (MediaStore.reference allows it)
CATALOGUE_MAX = 1 << 20
BLOCKS_MAX = 500
CATALOGUE_KEYS = ("name", "namespace", "kind", "preset", "band", "may_cross_face", "license", "source", "use_when", "params", "samples",
                  "natural_duration", "runtimes", "engines", "tier")      # what the listing hands out of an entry; any other key is dropped
KINDS = ("overlay", "layout", "caption")
ANIMATION_KINDS = ("overlay",)                                           # M1: overlays only (OPEN-4)
SLOT_TYPES = ("image", "clip")
HEX64 = re.compile(r"[0-9a-f]{64}")
PARAMS_MAX_BYTES = 8 * 1024
BLOCK_PARAMS_TIMEOUT = 60
WHY = ("kind", "no_preset", "slot", "engine", "not_configured")           # why a block cannot be added now, in the order they are tested


class CatalogueError(Exception):
    """A refusal to read the catalogue, with a closed `code`: `catalogue_unreadable` or `catalogue_stale`."""

    def __init__(self, code: str):
        super().__init__(code)
        self.code = code


def _read(path: str) -> bytes:
    """The bytes of one file (never through a symbolic link), at most CATALOGUE_MAX, or CatalogueError("catalogue_unreadable")."""
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
        with os.fdopen(fd, "rb") as f:
            data = f.read(CATALOGUE_MAX + 1)
    except OSError:
        raise CatalogueError("catalogue_unreadable") from None
    if len(data) > CATALOGUE_MAX:
        raise CatalogueError("catalogue_unreadable")
    return data


def _is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def _entry(item, seen: set) -> dict:
    bad = CatalogueError("catalogue_unreadable")
    if not isinstance(item, dict):
        raise bad
    name = item.get("name")
    if not (isinstance(name, str) and captions.BLOCK_NAME.fullmatch(name)) or name in seen:
        raise bad
    seen.add(name)
    if item.get("kind") not in KINDS:
        raise bad
    preset = item.get("preset")
    if preset is not None and not (isinstance(preset, str) and captions.PRESET_NAME.fullmatch(preset)):
        raise bad
    params = item.get("params")
    if not isinstance(params, dict) or len(params) > captions.PARAMS_MAX:
        raise bad
    for key, spec in params.items():
        if not (isinstance(key, str) and captions.PARAM_NAME.fullmatch(key)) or not isinstance(spec, dict) \
                or not isinstance(spec.get("type"), (str, list)):
            raise bad
    engines = item.get("engines")
    if not isinstance(engines, list) or not all(isinstance(e, str) for e in engines):
        raise bad
    if not isinstance(item.get("samples"), list):
        raise bad
    use = item.get("use_when")
    if not isinstance(use, str) or len(use) > 120:
        raise bad
    if item.get("natural_duration") is not None and not _is_number(item["natural_duration"]):
        raise bad
    return {k: item[k] for k in CATALOGUE_KEYS if k in item}


def read_catalogue(root: str) -> dict:
    """The catalogue as data, our fields only: {"blocks_sha256", "engines": {name: {"presets", "runtimes"}}, "blocks": {name: entry}}.
    CatalogueError `catalogue_unreadable` for a missing, oversized, linked or malformed file, `catalogue_stale` when `blocks_sha256` is not
    the sha256 of pins.json."""
    raw, pins = _read(os.path.join(root, *CATALOGUE)), _read(os.path.join(root, *PINS))
    try:
        doc = json.loads(raw.decode("utf-8"))
    except (ValueError, UnicodeDecodeError, RecursionError):
        raise CatalogueError("catalogue_unreadable") from None
    bad = CatalogueError("catalogue_unreadable")
    if not isinstance(doc, dict) or doc.get("schema_version") != 1 or not isinstance(doc.get("engines"), dict) \
            or not isinstance(doc.get("blocks"), list) or len(doc["blocks"]) > BLOCKS_MAX:
        raise bad
    digest = doc.get("blocks_sha256")
    if not (isinstance(digest, str) and HEX64.fullmatch(digest)):
        raise bad
    if hashlib.sha256(pins).hexdigest() != digest:
        raise CatalogueError("catalogue_stale")
    engines = {}
    for name, value in doc["engines"].items():
        if not (isinstance(name, str) and captions.PRESET_NAME.fullmatch(name)) or not isinstance(value, dict):
            raise bad
        presets, runtimes = value.get("presets"), value.get("runtimes")
        if not isinstance(presets, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in presets.items()) \
                or not isinstance(runtimes, list) or not all(isinstance(r, str) for r in runtimes):
            raise bad
        engines[name] = {"presets": dict(presets), "runtimes": list(runtimes)}
    seen, blocks = set(), {}
    for item in doc["blocks"]:
        entry = _entry(item, seen)
        blocks[entry["name"]] = entry
    return {"blocks_sha256": digest, "engines": engines, "blocks": blocks}


def engine_name(root: str, implementation=None):
    """The implementation the resolver gives `renderer:video` with the environment MediaEngine passes and the implementation the project's
    `media.renderer` names (None: the resolver decides), or None when none is configured."""
    try:
        r = project_config.resolver(root)
        return r.resolve(CLASS, root=root, env=r.provider_environment(CLASS, None, ()), implementation=implementation)["implementation"]
    except (project_config.ConfigError, ValueError, LookupError):     # UnknownClass is a ValueError, Unresolved a LookupError
        return None


def why_not(entry: dict, engine):
    """The first word of WHY that holds for this block, or None when it can be added now."""
    if entry["kind"] not in ANIMATION_KINDS:
        return "kind"
    if entry["preset"] is None:
        return "no_preset"
    if any(isinstance(spec["type"], list) or spec["type"] in SLOT_TYPES for spec in entry["params"].values()):
        return "slot"
    if engine is not None and engine not in entry["engines"]:
        return "engine"
    if engine is None:
        return "not_configured"
    return None


def listing(root: str, implementation=None) -> dict:
    """What the operation `video-catalogue` returns: {"engine", "blocks_sha256", "animations_max", "beats_max", "presets", "blocks": [entry +
    "addable" and "why"] sorted by name}. CatalogueError when the catalogue cannot be read."""
    found = read_catalogue(root)
    engine = engine_name(root, implementation)
    rows = []
    for name in sorted(found["blocks"]):
        entry = found["blocks"][name]
        why = why_not(entry, engine)
        rows.append(dict(entry, addable=why is None, why=why))
    presets = (found["engines"].get(engine) or {}).get("presets") if engine is not None else None
    return {"engine": engine, "blocks_sha256": found["blocks_sha256"], "animations_max": captions.ANIMATIONS_MAX,
            "beats_max": captions.BEATS_MAX, "presets": dict(presets or {}), "blocks": rows}


def engine_of(ctx: dict):
    """The media engine of this project (a seam: a test puts a fake in its place)."""
    store = ops_step_seams.MediaStore(ctx)
    return ops_step_seams.MediaEngine(store.root(), store.renderer())


_CODES = {"kind": "animation_kind", "no_preset": "block_no_preset", "slot": "slot_not_supported", "engine": "block_not_on_engine",
          "not_configured": "not_configured"}


def _shape(params, where: str) -> dict:
    """The parameters as the caller may send them to the checker, NFC and stripped for text, or CaptionError("bad_params")."""
    bad = captions.CaptionError("bad_params", f"{where}.params")
    if not isinstance(params, dict) or len(params) > captions.PARAMS_MAX:
        raise bad
    out = {}
    for key, value in params.items():
        if not (isinstance(key, str) and captions.PARAM_NAME.fullmatch(key)):
            raise bad
        if isinstance(value, str):
            if len(value) > captions.PARAM_TEXT_MAX:
                raise bad
        elif not _is_number(value):
            raise bad
        out[key] = value
    return out


def _reason(e, where: str) -> "captions.CaptionError":
    """The CaptionError for a refusal or failure of the engine."""
    if e.code == "refused":
        found = re.fullmatch(r"([a-z_]{1,40}) ([A-Za-z0-9_.:\[\]-]{1,80})", e.reason or "")
        if not found:
            return captions.CaptionError("block_check_failed", where)
        code, field = found.group(1), found.group(2)
        return captions.CaptionError(code, f"{where}.{field}" if field.startswith("params") else f"{where}.block")
    if e.code == "not_configured":
        return captions.CaptionError("not_configured", where)
    return captions.CaptionError("block_check_failed", where)


def checker(ctx: dict):
    """The `animate(block, params, where)` callable of captions.apply_edits. It reads nothing until its first call. A call returns {"block",
    "preset", "params"} (the parameters as the renderer's own checker accepted them) or raises a captions.CaptionError; the refused text is
    never in it."""
    state = {}

    def animate(block, params, where):
        if not (isinstance(block, str) and captions.BLOCK_NAME.fullmatch(block)):
            raise captions.CaptionError("bad_block", f"{where}.block")
        root = ops_step_seams.MediaStore(ctx).root()
        try:
            if "catalogue" not in state:
                state["catalogue"] = read_catalogue(root)
                state["engine"] = engine_name(root, ops_step_seams.MediaStore(ctx).renderer())
        except CatalogueError as e:
            raise captions.CaptionError(e.code, f"{where}.block") from None
        entry = state["catalogue"]["blocks"].get(block)
        if entry is None:
            raise captions.CaptionError("unknown_block", f"{where}.block")
        why = why_not(entry, state["engine"])
        if why is not None:
            raise captions.CaptionError(_CODES[why], f"{where}.block")
        cleaned = _shape(params, where)
        for key, value in list(cleaned.items()):
            spec = entry["params"].get(key)
            if isinstance(value, str) and isinstance(spec, dict) and spec.get("type") == "text":
                cleaned[key] = unicodedata.normalize("NFC", value).strip()
        if len(json.dumps(cleaned, ensure_ascii=False).encode("utf-8")) > PARAMS_MAX_BYTES:
            raise captions.CaptionError("bad_params", f"{where}.params")
        fd, path = tempfile.mkstemp(prefix="block-params-", suffix=".json")
        try:
            with os.fdopen(fd, "wb") as f:
                os.fchmod(f.fileno(), 0o600)
                f.write(json.dumps(cleaned, ensure_ascii=False).encode("utf-8"))
            flags = ["--block", block, "--params", path, "--vocabulary", ops_step_seams.MediaStore(ctx).reference(VOCABULARY)]
            try:
                done = engine_of(ctx).call(CLASS, VERB, flags, BLOCK_PARAMS_TIMEOUT)
            except ops_step_seams.StepServiceError as e:
                raise _reason(e, where) from None
        finally:
            try:
                os.unlink(path)
            except OSError:
                pass
        if not (isinstance(done, dict) and done.get("ok") is True and done.get("block") == block and done.get("params") == sorted(cleaned)):
            raise captions.CaptionError("block_check_failed", where)
        return {"block": block, "preset": entry["preset"], "params": cleaned}

    return animate


