"""The catalogue of animation blocks: what a block is (block.json, or an entry of the hf: allowlist), which engine can draw it, the
check of its parameters (the renderer-side checker, decision VD15), and the one pins file that names every block file by sha256.

A block is named `<namespace>:<name>`. `oh:` blocks are ours (blocks/oh/<name>/); `hf:` blocks come from the HyperFrames registry,
admitted by the committed allowlist (blocks/hf/allowlist.json) or ported under blocks/hf/<name>/ (V3b). An engine
(blocks/engines/<engine>.json) runs one or more drawing runtimes and names the block that draws each preset by default; it draws a block
that has an implementation for a runtime it runs and refuses any other (`block_not_on_engine`, naming its own block for the preset).
The catalogue file (blocks/catalogue.json) is generated from these files, never by hand (VD13). Both engines import this module; it
imports nothing of the browser, the frames or the host. Standard library only.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import re

from _assets import read_regular
from _text import Refusal
from _vocab import check_param

HERE = os.path.dirname(os.path.abspath(__file__))
BLOCKS_DIR = os.path.join(HERE, "blocks")
MAX_FILE = 1 << 20
SCHEMA_VERSION = 1
SOURCES = {"oh": "openhora", "hf": "hyperframes-registry"}
RUNTIMES = ("renderat", "gsap")
BANDS = {"overlay": "card", "layout": "frame", "caption": "caption"}
LICENSES = ("MIT", "Apache-2.0", "OFL-1.1")
PARAM_TYPES = ("text", "icon", "color", "choice", "image", "clip", "number")
_SHORT = r"[a-z][a-z0-9-]{0,39}"
_FILE = r"[a-z][a-z0-9-]{0,30}\.html"
NAME = re.compile(r"(oh|hf):" + _SHORT)
FILE_NAME = re.compile(_FILE)
IMPLEMENTATION = re.compile(r"(oh|hf)/%s/%s" % (_SHORT, _FILE))
PINNED = re.compile(r"engines/%s\.json|hf/allowlist\.json|(oh|hf)/%s/(block\.json|%s)" % (_SHORT, _SHORT, _FILE))
UNPINNED = ("pins.json", "catalogue.json", "block.schema.json")
HEX64 = re.compile(r"[0-9a-f]{64}")
HEX40 = re.compile(r"[0-9a-f]{40}")
PRESET = re.compile(r"[a-z][a-z0-9_]{0,31}")
PARAM_NAME = re.compile(r"[a-z][a-z0-9_]{0,31}")
CHOICE = re.compile(r"[a-z0-9][a-z0-9_-]{0,31}")
LINE = re.compile(r"[^\x00-\x1f\x7f-\x9f<>]{3,120}")
NOTICE = re.compile(r"[^\x00-\x1f\x7f-\x9f<>]{1,200}")
REGISTRY_PATH = re.compile(r"[a-z0-9][a-z0-9._-]{0,60}(/[a-z0-9][a-z0-9._-]{0,60}){0,4}")
BLOCK_REQUIRED = frozenset(("name", "kind", "preset", "band", "may_cross_face", "license", "source", "use_when", "params", "samples",
                            "natural_duration", "implementations"))
HF_KEYS = frozenset(("tier", "commit", "notice", "files"))
BLOCK_KEYS = BLOCK_REQUIRED | HF_KEYS
PARAM_KEYS = frozenset(("type", "required", "default", "max", "max_items", "pattern", "values", "min", "integer"))
ENGINE_KEYS = frozenset(("schema_version", "note", "runtimes", "presets", "engine"))
ALLOWLIST_KEYS = frozenset(("schema_version", "note", "registry_commit", "blocks"))
CATALOGUE_FIELDS = ("name", "kind", "preset", "band", "may_cross_face", "license", "source", "use_when", "params", "samples",
                    "natural_duration")
PINS_NOTE = ("sha256 of every block file, every engines file and the hf: allowlist. A file whose hash differs is refused, and a render "
             "records the sha256 of this file as blocks_sha256. Rewritten by `ffmpeg.py pin-blocks --confirmed` after a reviewed change, "
             "together with catalogue.json.")
CATALOGUE_NOTE = ("Generated by `python3 providers/renderer/ffmpeg.py pin-blocks --confirmed` from the oh: manifests "
                  "(blocks/oh/*/block.json), the hf: blocks (blocks/hf/) and the committed hf: allowlist, never from an image and never by "
                  "hand (decision VD13). A test holds it equal to what the generator writes. Our fields only: no registry text.")


def field_of(rel: str) -> str:
    """A blocks path as a refusal field (the host keeps no '/' in a field)."""
    return rel.replace("/", ":")[:80]


def block_of(rel: str) -> str:
    """'oh/keyword/renderat.html' -> 'oh:keyword'."""
    ns, short = rel.split("/")[:2]
    return "%s:%s" % (ns, short)


# ---------------------------------------------------------------- the small checks

def _fail(where: str):
    raise Refusal("block_schema", where[:80])


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _is_num(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def _is_str(value, pattern) -> bool:
    return isinstance(value, str) and pattern.fullmatch(value) is not None


# ---------------------------------------------------------------- the pins file

def parse_pins(raw: bytes) -> dict:
    """The `files` map of a pins.json: every key a pinnable path, every value a sha256."""
    try:
        doc = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError):
        raise Refusal("blocks_unreadable", "pins.json") from None
    if not isinstance(doc, dict) or set(doc) != {"note", "files"} or not isinstance(doc["note"], str) or not isinstance(doc["files"], dict):
        _fail("pins.json")
    for rel, digest in doc["files"].items():
        if not _is_str(rel, PINNED) or not _is_str(digest, HEX64):
            _fail("pins.json")
    return doc["files"]


def read_pins(blocks_dir: str = BLOCKS_DIR) -> tuple:
    raw = read_regular(os.path.join(blocks_dir, "pins.json"), MAX_FILE, "blocks_unreadable", "pins.json")
    return raw, parse_pins(raw)


# ---------------------------------------------------------------- block, engine and allowlist forms

def check_param_spec(spec, where: str) -> None:
    """The rules of 5.2 for one parameter: the vocabulary's shape plus the `number` type."""
    if not isinstance(spec, dict) or not set(spec) <= PARAM_KEYS or "type" not in spec:
        _fail(where)
    kind = spec["type"]
    if isinstance(kind, list):
        if not kind or len(set(kind)) != len(kind) or any(k not in ("image", "clip") for k in kind):
            _fail(where)
        kind = "slot"
    elif kind not in PARAM_TYPES:
        _fail(where)
    elif kind in ("image", "clip"):
        kind = "slot"
    if "required" in spec and not isinstance(spec["required"], bool):
        _fail(where)
    rest = set(spec) - {"type", "required"}
    if kind == "text":
        if rest - {"max", "max_items", "pattern"} or not _is_int(spec.get("max")) or not 1 <= spec["max"] <= 240:
            _fail(where)
        if "max_items" in spec and (not _is_int(spec["max_items"]) or not 1 <= spec["max_items"] <= 8):
            _fail(where)
        if "pattern" in spec:
            if not isinstance(spec["pattern"], str) or len(spec["pattern"]) > 80:
                _fail(where)
            try:
                re.compile(spec["pattern"])
            except re.error:
                _fail(where)
    elif kind == "choice":
        values = spec.get("values")
        if rest - {"values", "default"} or not isinstance(values, list) or not 1 <= len(values) <= 20 or len(set(map(str, values))) != len(values) \
                or not all(_is_str(v, CHOICE) for v in values):
            _fail(where)
        if "default" in spec and spec["default"] not in values:
            _fail(where)
    elif kind == "number":
        lo, hi = spec.get("min"), spec.get("max")
        if rest - {"min", "max", "integer", "default"} or not _is_num(lo) or not _is_num(hi) or lo > hi:
            _fail(where)
        if "integer" in spec and not isinstance(spec["integer"], bool):
            _fail(where)
        if "default" in spec and (not _is_num(spec["default"]) or not lo <= spec["default"] <= hi):
            _fail(where)
    elif rest:                                                       # icon, color, image, clip: no bounds
        _fail(where)


def check_block(obj, where: str, namespace: str, short=None, pinned=None, registry_commit=None) -> dict:
    """The rules of 5.2 for a block.json (`short` given) or an allowlist entry (`short` None). Returns a copy with the block's keys."""
    if not isinstance(obj, dict):
        _fail(where)
    from_file = short is not None
    allowed = BLOCK_KEYS | ({"schema_version"} if from_file else frozenset())
    if not set(obj) <= allowed or not BLOCK_REQUIRED <= set(obj) or (from_file and "schema_version" not in obj):
        _fail(where)
    if from_file and (not _is_int(obj["schema_version"]) or obj["schema_version"] != SCHEMA_VERSION):
        _fail(where)
    if namespace == "oh" and (not from_file or HF_KEYS & set(obj)):
        _fail(where)
    if namespace not in SOURCES:
        _fail(where)
    name = obj["name"]
    if not _is_str(name, NAME) or name.split(":")[0] != namespace or (from_file and name != namespace + ":" + short):
        _fail(where)
    kind = obj["kind"]
    if kind not in BANDS:
        _fail(where)
    preset = obj["preset"]
    if kind == "caption":
        if preset != "caption":
            _fail(where)
    elif preset is not None and (not _is_str(preset, PRESET) or preset == "caption"):
        _fail(where)
    if obj["band"] != BANDS[kind]:
        _fail(where)
    cross = obj["may_cross_face"]
    if not isinstance(cross, bool) or (cross and (obj["band"] != "frame" or namespace == "hf")):
        _fail(where)
    lic = obj["license"]
    if not isinstance(lic, list) or not 1 <= len(lic) <= 3 or len(set(map(str, lic))) != len(lic) or any(x not in LICENSES for x in lic):
        _fail(where)
    if obj["source"] != SOURCES[namespace]:
        _fail(where)
    if not _is_str(obj["use_when"], LINE):
        _fail(where)
    params = obj["params"]
    if not isinstance(params, dict) or len(params) > 12:
        _fail(where)
    for pname, spec in params.items():
        if not _is_str(pname, PARAM_NAME):
            _fail(where)
        check_param_spec(spec, where)
        if namespace == "hf" and (spec["type"] in ("image", "clip") or isinstance(spec["type"], list)):
            _fail(where)
    samples = obj["samples"]
    if not isinstance(samples, list) or not 1 <= len(samples) <= 5:
        _fail(where)
    for sample in samples:
        if not isinstance(sample, dict) or not set(sample) <= set(params) or any(s.get("required") and n not in sample for n, s in params.items()):
            _fail(where)
    duration = obj["natural_duration"]
    if duration is None:
        if kind != "caption":
            _fail(where)
    elif not _is_num(duration) or not 0.2 <= duration <= 60:
        _fail(where)
    impl = obj["implementations"]
    if not isinstance(impl, dict) or not 1 <= len(impl) <= 2 or any(k not in RUNTIMES or not _is_str(v, FILE_NAME) for k, v in impl.items()):
        _fail(where)
    if namespace == "hf":
        if not _is_str(obj.get("commit"), HEX40) or not isinstance(obj.get("notice"), str) or not NOTICE.fullmatch(obj["notice"]):
            _fail(where)
        if from_file:
            if obj.get("tier") != "B" or "files" in obj:
                _fail(where)
        else:
            files = obj.get("files")
            if obj.get("tier") != "A" or obj["commit"] != registry_commit or not isinstance(files, dict) or not 1 <= len(files) <= 50 \
                    or not all(_is_str(k, REGISTRY_PATH) and _is_str(v, HEX64) for k, v in files.items()):
                _fail(where)
    if from_file:
        for value in impl.values():
            if "%s/%s/%s" % (namespace, short, value) not in (pinned or {}):
                _fail(where)
    elif any(v not in obj["files"] for v in impl.values()):
        _fail(where)
    return {k: v for k, v in obj.items() if k != "schema_version"}


def check_engine(obj, name: str) -> dict:
    where = "engines:%s.json" % name
    if not isinstance(obj, dict) or set(obj) != ENGINE_KEYS or not _is_int(obj["schema_version"]) or obj["schema_version"] != SCHEMA_VERSION \
            or obj["engine"] != name or not isinstance(obj["note"], str):
        _fail(where)
    runtimes = obj["runtimes"]
    if not isinstance(runtimes, list) or not runtimes or len(set(map(str, runtimes))) != len(runtimes) or any(r not in RUNTIMES for r in runtimes):
        _fail(where)
    presets = obj["presets"]
    if not isinstance(presets, dict) or not presets or not all(_is_str(k, PRESET) and _is_str(v, NAME) for k, v in presets.items()):
        _fail(where)
    return obj


# ---------------------------------------------------------------- the catalogue

def load_catalogue(blocks_dir: str = BLOCKS_DIR, expect_sha256=None) -> dict:
    """Load every pinned file of `blocks_dir`, each checked against blocks/pins.json, and every form against its rules."""
    raw, files = read_pins(blocks_dir)
    digest = hashlib.sha256(raw).hexdigest()
    if expect_sha256 is not None and digest != expect_sha256:
        raise Refusal("blocks_changed", "blocks")
    docs = {}
    for rel in sorted(files):
        data = read_regular(os.path.join(blocks_dir, rel), MAX_FILE, "blocks_unreadable", field_of(rel))
        if hashlib.sha256(data).hexdigest() != files[rel]:
            raise Refusal("block_hash", field_of(rel))
        if rel.endswith(".json"):
            try:
                docs[rel] = json.loads(data.decode("utf-8"))
            except (UnicodeDecodeError, ValueError):
                _fail(field_of(rel))
    if "hf/allowlist.json" not in docs:
        raise Refusal("blocks_unreadable", "hf:allowlist.json")
    allow = docs["hf/allowlist.json"]
    if not isinstance(allow, dict) or set(allow) != ALLOWLIST_KEYS or not _is_int(allow["schema_version"]) or allow["schema_version"] != SCHEMA_VERSION \
            or not isinstance(allow["note"], str) or not isinstance(allow["blocks"], list):
        _fail("hf:allowlist.json")
    commit = allow["registry_commit"]
    if not (commit is None and not allow["blocks"]) and not _is_str(commit, HEX40):
        _fail("hf:allowlist.json")
    blocks, engines = {}, {}
    for k, entry in enumerate(allow["blocks"]):
        block = check_block(entry, "hf:allowlist[%d]" % k, "hf", registry_commit=commit)
        if block["name"] in blocks:
            _fail(block["name"])
        blocks[block["name"]] = block
    for rel in sorted(docs):
        parts = rel.split("/")
        if len(parts) == 3 and parts[2] == "block.json":
            block = check_block(docs[rel], field_of(rel), parts[0], parts[1], files)
            if block["name"] in blocks:
                _fail(block["name"])
            blocks[block["name"]] = block
        elif parts[0] == "engines":
            engine = parts[1][:-len(".json")]
            engines[engine] = check_engine(docs[rel], engine)
    for ename, engine in engines.items():
        for preset, bname in engine["presets"].items():
            block = blocks.get(bname)
            if block is None or block["preset"] != preset or not set(engine["runtimes"]) & set(block["implementations"]):
                _fail("engines:%s.json" % ename)
    return {"dir": os.path.abspath(blocks_dir), "sha256": digest, "files": files, "blocks": blocks, "engines": engines}


def engines_of(catalogue: dict, block: dict) -> list:
    return sorted(n for n, e in catalogue["engines"].items() if set(e["runtimes"]) & set(block["implementations"]))


def implementation(catalogue: dict, block: dict, engine: str) -> str:
    """The page that draws `block` on `engine`: the first of the engine's runtimes the block implements, as "<ns>/<name>/<file>"."""
    for runtime in catalogue["engines"][engine]["runtimes"]:
        if runtime in block["implementations"]:
            ns, short = block["name"].split(":")
            return "%s/%s/%s" % (ns, short, block["implementations"][runtime])
    raise Refusal("block_not_on_engine", block["name"])


def resolve(catalogue: dict, engine: str, preset: str, name, field: str) -> dict:
    """The block that draws a beat of `preset` on `engine`: the named one, else the engine's default for the preset."""
    if engine not in catalogue["engines"]:
        raise Refusal("engine_unknown", str(engine)[:60])
    eng = catalogue["engines"][engine]
    if preset not in eng["presets"]:
        raise Refusal("preset_not_on_engine", field)
    default = eng["presets"][preset]
    if name is None:
        name = default
    elif not _is_str(name, NAME) or name not in catalogue["blocks"]:
        raise Refusal("block_unknown", field)
    block = catalogue["blocks"][name]
    if not set(eng["runtimes"]) & set(block["implementations"]):
        raise Refusal("block_not_on_engine", default)
    if block["preset"] != preset:
        raise Refusal("block_preset_mismatch", field)
    return block


def _check_number(spec: dict, value, field: str):
    if not _is_num(value) or (spec.get("integer") and not _is_int(value)) or not spec["min"] <= value <= spec["max"]:
        raise Refusal("bad_number", field)
    return value


def check_params(block: dict, params, vocab: dict, field: str = "params") -> dict:
    """The renderer-side checker (VD15): one block's parameters against its declaration. No undeclared name, every required one
    present, every value of its type and bounds. Defaults are not filled in. Returns the cleaned object."""
    if not isinstance(params, dict):
        raise Refusal("params_not_object", field)
    declared = block["params"]
    out = {}
    for pname, value in params.items():
        if pname not in declared:
            raise Refusal("undeclared_param", "%s.%s" % (field, pname))
        spec = declared[pname]
        if spec["type"] == "number":
            out[pname] = _check_number(spec, value, "%s.%s" % (field, pname))
        else:
            out[pname] = check_param(vocab, spec, "%s.%s" % (field, pname), value)
    for pname, spec in declared.items():
        if spec.get("required") and pname not in out:
            raise Refusal("missing_param", "%s.%s" % (field, pname))
    return out


def templates_for(catalogue: dict, engine: str, timeline: dict, vocab: dict, with_caption: bool) -> tuple:
    """For a timeline: ({key: page path}, [page paths to load]). The key of the caption is "caption", the key of a beat's page is its
    block's name. Sets each beat's `block`. Every beat's parameters are checked on the block that draws it."""
    templates = {"caption": implementation(catalogue, resolve(catalogue, engine, "caption", None, "edl.captions"), engine)}
    names = [templates["caption"]] if with_caption else []
    for e in timeline["beats"]:
        field = "beats.%s" % e["id"]
        blk = resolve(catalogue, engine, e["preset"], e.get("block"), field)
        check_params(blk, e["params"], vocab, field + ".params")
        e["block"] = blk["name"]
        templates[blk["name"]] = implementation(catalogue, blk, engine)
        names.append(templates[blk["name"]])
    return templates, names


def catalogue_doc(catalogue: dict) -> dict:
    blocks = []
    for name in sorted(catalogue["blocks"]):
        block = catalogue["blocks"][name]
        entry = {k: block[k] for k in CATALOGUE_FIELDS}
        entry["namespace"] = name.split(":")[0]
        entry["runtimes"] = sorted(block["implementations"])
        entry["engines"] = engines_of(catalogue, block)
        if "tier" in block:
            entry["tier"] = block["tier"]
        blocks.append(entry)
    return {"schema_version": SCHEMA_VERSION, "note": CATALOGUE_NOTE, "blocks_sha256": catalogue["sha256"],
            "engines": {e: {"runtimes": v["runtimes"], "presets": v["presets"]} for e, v in sorted(catalogue["engines"].items())},
            "blocks": blocks}


def catalogue_bytes(catalogue: dict) -> bytes:
    return (json.dumps(catalogue_doc(catalogue), indent=1, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


# ---------------------------------------------------------------- maintainer tools

def write_pins(blocks_dir: str = BLOCKS_DIR) -> dict:
    """Maintainer tool: hash every block file of the folder into pins.json. A file that is not a block file is refused."""
    files = {}
    for root, dirs, names in os.walk(blocks_dir):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for name in sorted(names):
            if name.startswith("."):
                continue
            rel = os.path.relpath(os.path.join(root, name), blocks_dir).replace(os.sep, "/")
            if rel in UNPINNED:
                continue
            if not PINNED.fullmatch(rel):
                raise Refusal("block_file_unknown", field_of(rel))
            files[rel] = hashlib.sha256(read_regular(os.path.join(blocks_dir, rel), MAX_FILE, "blocks_unreadable", field_of(rel))).hexdigest()
    with open(os.path.join(blocks_dir, "pins.json"), "w", encoding="utf-8") as fh:
        json.dump({"note": PINS_NOTE, "files": files}, fh, indent=1, sort_keys=True)
        fh.write("\n")
    return files


def write_catalogue(blocks_dir: str = BLOCKS_DIR) -> str:
    catalogue = load_catalogue(blocks_dir)
    with open(os.path.join(blocks_dir, "catalogue.json"), "wb") as fh:
        fh.write(catalogue_bytes(catalogue))
    return catalogue["sha256"]
